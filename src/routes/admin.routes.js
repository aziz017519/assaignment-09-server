import { Router } from 'express';
import { adminSchemas, deleteService, getBookings, getPayments, getServices, getStats, getTransactions, getUsers, updateBookingStatus, updateServiceApproval, updateServiceStatus, updateUserRole, } from '../controllers/admin.controller.js';
import { validate } from '../middlewares/validate.js';
import { verifyAdmin } from '../middlewares/verifyAdmin.js';
import { verifyToken } from '../middlewares/verifyToken.js';
const router = Router();
router.use(verifyToken, verifyAdmin);
router.get('/users', validate({ query: adminSchemas.listUsers }), getUsers);
router.patch('/users/:id/role', validate({ params: adminSchemas.params, body: adminSchemas.role }), updateUserRole);
router.get('/services', validate({ query: adminSchemas.listServices }), getServices);
router.patch('/services/:id/status', validate({ params: adminSchemas.params, body: adminSchemas.serviceStatus }), updateServiceStatus);
router.patch('/services/:id/approval', validate({ params: adminSchemas.params, body: adminSchemas.approval }), updateServiceApproval);
router.delete('/services/:id', validate({ params: adminSchemas.params }), deleteService);
router.get('/bookings', validate({ query: adminSchemas.listBookings }), getBookings);
router.patch('/bookings/:id/status', validate({ params: adminSchemas.params, body: adminSchemas.bookingStatus }), updateBookingStatus);
router.get('/payments', getPayments);
router.get('/transactions', validate({ query: adminSchemas.listTransactions }), getTransactions);
router.get('/stats', getStats);
export default router;
